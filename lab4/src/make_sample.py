def make_sample(path=Path("data/raw/tickets.csv")):
    rows = []
    start = datetime(2026, 9, 1, 9)
    for i in range(20):
        for category, phrases in SAMPLES.items():
            n = len(rows)
            rows.append({"ticket_id": f"T-{n + 1:04d}",
                         "created_at": (start + timedelta(hours=n)).isoformat(),
                         "text": phrases[i], "channel": ["web", "email", "chat"][(n // 3) % 3],
                         "category": category})
    rows[5]["channel"] = ""  # Пропуск, который заполнит препроцессор.
    for i in (0, 1):
        row = dict(rows[i], ticket_id=f"T-{len(rows) + 1:04d}")
        row["text"] = "  " + row["text"].upper() + "!!!  "
        rows.append(row)
    for text in ("", "   "):
        rows.append({"ticket_id": f"T-{len(rows) + 1:04d}",
                     "created_at": (start + timedelta(days=4)).isoformat(),
                     "text": text, "channel": "chat", "category": "TECHNICAL"})
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    return path


if __name__ == "__main__":
    print(make_sample())
